def guess_category(title: str, lead: str, current_cats: list) -> list:
    """Возвращает список категорий для статьи."""
    text = f"{title} {lead}".lower()

    # Если уже стоит хорошая новая категория — не трогаем
    good = {"Дайджесты", "Крепкий алкоголь", "Пиво и сидр", "Коктейли и безалкогольное",
            "Креплёные и десертные вина", "Российское виноделие", "Вино и еда"}
    for c in current_cats or []:
        if c in good:
            return current_cats[:2]

    for main_cat, sec_cat, keys in RULES:
        for k in keys:
            if k in text:
                # если secondary совпадает с main — только main
                if sec_cat == main_cat:
                    return [main_cat]
                return [main_cat, sec_cat]

    # fallback: если ничего не подошло — оставляем как есть
    return current_cats or ["Винные новости"]


def main():
    if not POSTS_INDEX.exists():
        print(f"Нет файла: {POSTS_INDEX}")
        return 1

    posts = json.loads(POSTS_INDEX.read_text(encoding="utf-8"))
    print(f"Всего статей в индексе: {len(posts)}")

    changed = 0
    for p in posts:
        old = list(p.get("categories") or [])
        new = guess_category(p.get("title", ""), p.get("lead", ""), old)
        if new != old:
            print(f"  «{p.get('title', '')[:60]}»")
            print(f"     было: {old}")
            print(f"     стало: {new}")
            p["categories"] = new
            changed += 1

    print(f"\nИзменено: {changed} из {len(posts)}")

    POSTS_INDEX.write_text(json.dumps(posts, ensure_ascii=False, indent=2), encoding="utf-8")

    print("\nПересобираем главную index.html")
    html_renderer.rebuild_index()
    print("Готово")
    return 0


if __name__ == "__main__":
    sys.exit(main())
