"""
Одноразовый скрипт: переписывает кликбейтные заголовки в feed.xml
на нейтральные информативные. Дзен запрещает кликбейт (см. правила).

Кликбейт по Дзену:
- «Никто не объясняет...» — утаивание ключевой информации
- «Правда о...» — громкие заявления
- «Шокирующий...», «Ужасный...»
- «Ваши гости будут в шоке...»
- «...— а разница огромная» — манипулятивные обороты
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import claude_api
import feed_io
import html_renderer

# Признаки кликбейта в заголовках Дзена
CLICKBAIT_PATTERNS = [
    r"никто не",
    r"правда о ",
    r"правда об ",
    r"шок", r"ужас",
    r"в шоке",
    r"невероятн",
    r"скрывают",
    r"скрывает",
    r"раскрываем",
    r"что произошло когда",
    r"вы не поверите",
    r"тайн[аыу]",
    r"секрет",
    r"взорвал",
    r"вы будете",
    r"!{2,}",  # двойные восклицания
]


def is_clickbait(title: str) -> bool:
    t = title.lower()
    return any(re.search(p, t, re.IGNORECASE) for p in CLICKBAIT_PATTERNS)


SYSTEM = """Ты — редактор винного журнала AddWine. Тебе дают заголовок статьи, ты переписываешь его на нейтральный, информативный, БЕЗ КЛИКБЕЙТА.

Правила (по требованиям Дзена):
- НЕ использовать формулы: «Никто не объясняет», «Правда о», «Шок», «Ужас», «Скрывают», «Вы не поверите», «Тайна», «Секрет», «Взорвал»
- НЕ использовать множественные восклицания, многоточия с интригой
- Заголовок должен СРАЗУ раскрывать главное содержание статьи
- Тон спокойный, экспертный, информативный
- Длина: 40-100 знаков
- Можно начать с: «Как», «Почему», «Что», «Зачем», «Чем», «Гид по», «Разбор», числа («5 правил», «3 ошибки»), без знаков вопроса в конце
- Заголовок должен соответствовать содержанию

Примеры замен:
- «Никто не объясняет, чем винтажное игристое отличается от обычного — а разница огромная» →
  «Чем винтажное игристое вино отличается от безвинтажного: гид для покупателей»
- «Правда об органическом вине: что скрывают этикетки» →
  «Что означает маркировка «органическое» на бутылке вина»
- «5 признаков того, что вино в бокале испорчено» →
  «5 признаков испорченного вина: как определить до первого глотка»

Ответь в JSON: {"title": "новый заголовок"}"""


def rewrite_title(old: str, lead: str = "") -> str:
    user = f"Старый заголовок: {old}\n\nЛид статьи: {lead[:300]}\n\nПерепиши заголовок на нейтральный."
    result = claude_api.generate_json(SYSTEM, user, max_tokens=200, temperature=0.5)
    return result.get("title", old).strip()


def main():
    data = feed_io.read_feed()
    items = data["items"]
    print(f"Проверяем {len(items)} статей на кликбейт")

    changed = 0
    for it in items:
        old_title = it["title"]
        if is_clickbait(old_title):
            print(f"\n  КЛИКБЕЙТ: {old_title[:100]}")
            try:
                new_title = rewrite_title(old_title, it.get("description", ""))
                print(f"  → НОВЫЙ: {new_title}")
                it["title"] = new_title
                changed += 1
            except Exception as e:
                print(f"  [!] Claude упал: {e}")
        else:
            print(f"  OK: {old_title[:80]}")

    if changed == 0:
        print("\nКликбейта не найдено")
    else:
        print(f"\nПереписано {changed} заголовков. Сохраняем feed.xml")
        feed_io.write_feed(data["channel"], items)

    # обновим страницы статей и главную с новыми заголовками
    print("\nПерегенерируем HTML-страницы")
    html_renderer.rebuild_from_feed("https://feed.addwine.ru")

    return 0


if __name__ == "__main__":
    sys.exit(main())
