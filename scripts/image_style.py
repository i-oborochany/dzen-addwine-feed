def _load_log() -> list:
    if LOG_PATH.exists():
        try:
            return json.loads(LOG_PATH.read_text(encoding="utf-8"))
        except Exception:
            return []
    return []


def _save_log(log: list) -> None:
    LOG_PATH.write_text(json.dumps(log[-200:], ensure_ascii=False, indent=1), encoding="utf-8")


def _pick_scene(title: str, recent_keys: set):
    """Выбирает сцену: сначала тематически подходящую и свежую, иначе просто свежую."""
    t = (title or "").lower()
    fresh = [s for s in SCENES if s[0] not in recent_keys]
    if not fresh:
        fresh = list(SCENES)

    # тематический матч
    matched = [s for s in fresh if any(kw in t for kw in s[2])]
    pool = matched if matched else fresh
    return random.choice(pool)


def enrich(prompt: str, title: str = "") -> str:
    """
    Дописывает к промпту picture style-директиву со свежей сценой/ракурсом/светом.
    Логирует выбор чтобы не повторяться следующие AVOID_LAST публикаций.
    """
    log = _load_log()
    recent_keys = {e.get("scene") for e in log[-AVOID_LAST:]}
    recent_angles = {e.get("angle") for e in log[-4:]}
    recent_lights = {e.get("light") for e in log[-4:]}

    scene = _pick_scene(title, recent_keys)
    angle = random.choice([a for a in ANGLES if a not in recent_angles] or ANGLES)
    light = random.choice([l for l in LIGHTS if l not in recent_lights] or LIGHTS)

    log.append({
        "date": datetime.now(timezone.utc).isoformat()[:16],
        "scene": scene[0],
        "angle": angle,
        "light": light,
        "title": (title or "")[:80],
    })
    _save_log(log)

    directive = f"""

СЦЕНА (заменяет любые описания сцены выше — использовать ИМЕННО её, адаптировав под тему статьи):
{scene[1]}

РАКУРС: {angle}
СВЕТ И ПАЛИТРА: {light}
{QUALITY_RULES}"""

    print(f"  [image_style] сцена: {scene[0]}, ракурс: {angle[:30]}, свет: {light[:30]}")
    return prompt + directive


