def load_topics() -> list:
    return json.loads(TOPICS_PATH.read_text(encoding="utf-8"))["topics"]


def pick_topic(used_titles: list, history: list = None) -> str:
    """Выбирает следующую неиспользованную тему + стоп-лист + семантический дедуп 90 дней."""
    topics = load_topics()
    used_lower = [t.lower() for t in used_titles]
    fresh = [t for t in topics if not any(t.lower()[:30] in u for u in used_lower)]
    if not fresh:
        fresh = topics

    # Стоп-лист тем (не пишем про бокалы/штопоры/бренды AddWine)
    import stop_list
    filtered = stop_list.filter_topics(fresh)
    if filtered:
        fresh = filtered

    if history:
        import dedup
        no_dupes = dedup.filter_topics(fresh, history, days=90)
        if no_dupes:
            fresh = no_dupes
            print(f"  [dedup] после фильтра 90 дней осталось {len(fresh)} тем")
        else:
            print(f"  [dedup] ⚠️  все темы имеют семантический дубль за 90 дней")

    return fresh[0]


def write_russian_article(topic_idea: str, recent_titles: list, keywords_hint: str = "") -> dict:
    """Генерирует статью про российское виноделие на основе идеи."""
    history = "\n".join(f"- {t}" for t in recent_titles[:30]) if recent_titles else "(пусто)"

    seo_block = f"\n\n{keywords_hint}\n" if keywords_hint else ""

    user = f"""ИДЕЯ ДЛЯ СТАТЬИ: {topic_idea}

Уже публиковали за последние месяцы (не повторяйся):
{history}
{seo_block}
Напиши оригинальную статью на эту идею в патриотически-экспертном тоне. Соблюдай все требования к структуре, картинкам, заголовкам, категориям.

Ответ строго в JSON по схеме из системного промпта."""

    result = claude_api.generate_json(SYSTEM, user, max_tokens=8000, temperature=0.7)
    _validate(result)
    return result


def _validate(result: dict) -> None:
    required = ["titles", "title_chosen", "lead", "html", "image_prompts", "comment_question", "categories"]
    for f in required:
        if f not in result:
            raise RuntimeError(f"Поле '{f}' отсутствует в ответе Claude")
    if len(result["image_prompts"]) < 1:
        raise RuntimeError("image_prompts пустой")
    result["image_prompts"] = result["image_prompts"][:1]

    # категория всегда содержит "Российское виноделие" как основную
    cats = result.get("categories") or []
    if "Российское виноделие" not in cats:
        cats = ["Российское виноделие"] + [c for c in cats if c != "Российское виноделие"]
    result["categories"] = cats[:2]

    result["html"] = re.sub(r"  +", " ", result["html"])
