REPO_ROOT = Path(__file__).resolve().parent.parent


DIGEST_SYSTEM = """Ты — главный редактор винного журнала AddWine. Твоя задача — составить еженедельный дайджест винных событий из подборки новостей.

ПРИНЦИПЫ ДАЙДЖЕСТА
- Каждая новость — отдельный смысловой блок: заголовок-вариация исходного + 2-3 уникальных абзаца своими словами.
- Не копируй текст оригинала, а пересказывай факты экспертным редакторским языком.
- В конце каждого блока — короткая подпись источника: «По материалам [название источника]» БЕЗ ссылки.
- Тон: спокойный, экспертный, информативный, как у качественного отраслевого журнала.
- Без рекламы, без CTA, без упоминания AddWine.
- HTML-теги ТОЛЬКО: <p>, <h2>, <h3>, <h4>, <ul>, <ol>, <li>, <b>, <i>
- НЕ используй <a>, <strong>, <em>, <br>, <div>, <span>, <hr>. Ссылок наружу быть НЕ ДОЛЖНО.

СТРУКТУРА HTML-ДАЙДЖЕСТА
- В начале — короткий вступительный абзац (1-2 предложения), общая мысль о неделе.
- Затем для каждой новости отдельный блок ровно в таком порядке:
  <p>[[IMG_N]]</p>
  <h3>Заголовок блока</h3>
  <p>Первый абзац — что произошло, факт.</p>
  <p>Второй абзац — контекст, цифры, имена.</p>
  <p><i>По материалам {source}.</i></p>
- Между новостями оставляй пустую строку.

Где N — порядковый номер блока (1, 2, 3, ...). Эти плейсхолдеры будут заменены на картинки.
ВАЖНО: НЕ используй тег <a> со ссылкой на источник. Просто упомяни название источника в курсиве.

ЗАГОЛОВОК ДАЙДЖЕСТА
Информативный, нейтральный. Например:
- «Винные события недели: главные новости отрасли»
- «Главное в мире вина: дайджест за неделю»
- «Что произошло в винной индустрии: обзор недели»

КАТЕГОРИИ
Основная категория всегда: «Винные новости». Вторая опциональная: «Технологии и инновации» / «Вино и деньги» / «Вино, культура и личности».

ФОРМАТ ОТВЕТА — строго JSON без markdown:
{
  "title": "<заголовок дайджеста>",
  "lead": "<один абзац — короткий обзор главного>",
  "html": "<полный HTML дайджеста по структуре выше>",
  "categories": ["Винные новости", "доп. категория"]
}
"""


def build_digest(articles: list) -> dict:
    """
    Принимает список dict {source, source_url, title, lead, pub_date}
    Возвращает {title, lead, html, categories}
    """
    if not articles:
        raise RuntimeError("Нет статей для дайджеста")

    # ужимаем список для Claude (источники + заголовки + лиды)
    items_text = ""
    for i, art in enumerate(articles, 1):
        items_text += f"\n--- Новость #{i} ---\n"
        items_text += f"Источник: {art['source']}\n"
        items_text += f"URL источника: {art['source_url']}\n"
        items_text += f"Заголовок: {art['title']}\n"
        items_text += f"Лид: {art['lead']}\n"

    user = f"""Подборка {len(articles)} винных новостей за неделю:
{items_text}

Составь еженедельный дайджест по правилам из системного промпта. Используй ровно {len(articles)} плейсхолдеров [[IMG_1]]..[[IMG_{len(articles)}]] в порядке появления новостей."""

    result = claude_api.generate_json(DIGEST_SYSTEM, user, max_tokens=8000, temperature=0.7)
    _validate(result)
    return result


def _validate(result: dict) -> None:
    for f in ("title", "lead", "html", "categories"):
        if f not in result:
            raise RuntimeError(f"Поле {f} отсутствует в ответе Claude")
    cats = result.get("categories") or []
    if "Винные новости" not in cats:
        cats = ["Винные новости"] + [c for c in cats if c != "Винные новости"]
    result["categories"] = cats[:2]
    result["html"] = re.sub(r"  +", " ", result["html"])
