def _validate(result: dict) -> None:
    required = ["titles", "title_chosen", "lead", "html", "image_prompts", "cover_texts", "comment_question", "categories"]
    for f in required:
        if f not in result:
            raise RuntimeError(f"Поле '{f}' отсутствует в ответе Claude")
    if len(result["titles"]) < 1:
        raise RuntimeError("Нужно минимум 1 вариант заголовка")
    if len(result["image_prompts"]) < 1:
        raise RuntimeError("image_prompts пустой")
    result["image_prompts"] = result["image_prompts"][:1]
    if len(result["cover_texts"]) < 1:
        result["cover_texts"] = [result["title_chosen"]]

    # фильтруем категории по допустимому списку
    cats = [c for c in (result.get("categories") or []) if c in CATEGORIES]
    if not cats:
        cats = ["Дегустации и советы"]
    result["categories"] = cats[:2]

    result["html"] = re.sub(r"  +", " ", result["html"])
