def write_trend_article(seed_titles: list, recent_history: list, brand_colors: dict) -> dict:
    """
    Режим TREND: Claude сам выбирает тему из заголовков-затравок и пишет с нуля.
    Без CTA, без упоминания AddWine.
    """
    seeds_text = "\n".join(f"- {t}" for t in seed_titles[:30])
    history_text = "\n".join(f"- {t}" for t in recent_history) if recent_history else "(пусто)"

    user = f"""РЕЖИМ: ТРЕНДОВАЯ СТАТЬЯ (без CTA, без упоминания бренда)

Ниже — заголовки актуальных публикаций с топовых сайтов о вине (Дзен, Decanter, Wine Spectator, Simple Wine News, РБК Вино и др.). Это только намёки на актуальные темы — не пересказывай ни одну конкретную статью.

Заголовки-затравки:
{seeds_text}

Запрещённые темы (уже публиковались за последние 60 дней — НЕ повторяйся):
{history_text}

Твоя задача:
1. Выбери ОДНУ актуальную тему, которая интересна нашей аудитории и не повторяется с историей. Темы могут касаться: новостей о вине в России, виноделия, винных регионов и событий, винных аксессуаров (бокалы, штопоры, декантеры, аэраторы, хранение), сервировки, гастрономических пар.
2. Напиши на эту тему полностью оригинальную статью — со своей структурой, примерами, подачей. Не пересказывай конкретный источник.
3. В тексте НЕ упоминай AddWine, не давай ссылок, не делай CTA. Не добавляй блок «AddWine рекомендует».
4. Источник не указывай.

Выдай результат строго в JSON-формате, описанном в системном промпте."""

    result = claude_api.generate_json(SOMMELIER_SYSTEM, user, max_tokens=8000, temperature=0.8)
    _validate(result)
    return result


def write_content_plan_article(plan_row: dict) -> dict:
    """
    Режим CONTENT_PLAN: статья по строке контент-плана с CTA на категорию AddWine.
    """
    user = f"""РЕЖИМ: СТАТЬЯ ПО КОНТЕНТ-ПЛАНУ (статья №5 цикла) — с CTA и ссылкой

Строка контент-плана:
- Тема статьи: {plan_row['title']}
- Категория тематики: {plan_row['theme']}
- SEO-запрос (вписывай естественно в заголовок, первый абзац, подзаголовки): {plan_row['seo_query']}
- Текст CTA: {plan_row['cta_text']}
- Ссылка на категорию: {plan_row['promote_link']}
- Что продвигаем: {plan_row['promote_category']}

Твоя задача:
1. Напиши статью на эту тему. SEO-запрос должен встречаться естественно в заголовке (или одном из 3 вариантов), первом абзаце и хотя бы одном подзаголовке.
2. В САМОМ КОНЦЕ статьи добавь мягкий CTA-блок такого формата:

<h3>AddWine рекомендует</h3>
<p>[Связка темы статьи и категории аксессуара в 2–3 предложения, экспертным тоном.] [Объяснение, почему именно эта категория решает обсуждённую в статье проблему — 1–2 предложения.] {plan_row['cta_text']}: <a href="{plan_row['promote_link']}">смотреть подборку</a>.</p>

3. CTA должен быть один. Никаких других ссылок и упоминаний бренда в теле статьи.
4. ВАЖНО: статья должна быть про реальную пользу, а не рекламной. AddWine — это контекст в конце, а не суть.

Выдай результат строго в JSON-формате, описанном в системном промпте."""

    result = claude_api.generate_json(SOMMELIER_SYSTEM, user, max_tokens=8000, temperature=0.7)
    _validate(result)
    return result


def _validate(result: dict) -> None:
    """Проверяем что все обязательные поля на месте."""
    required = ["titles", "title_chosen", "lead", "html", "image_prompts", "cover_texts", "comment_question"]
    for f in required:
        if f not in result:
            raise RuntimeError(f"Поле '{f}' отсутствует в ответе Claude")

    if len(result["titles"]) < 1:
        raise RuntimeError("Нужно минимум 1 вариант заголовка")
    if len(result["image_prompts"]) != 4:
        while len(result["image_prompts"]) < 4:
            result["image_prompts"].append(result["image_prompts"][-1])
        result["image_prompts"] = result["image_prompts"][:4]
    if len(result["cover_texts"]) < 1:
        result["cover_texts"] = [result["title_chosen"]]

    # автозамена «—» на «-» внутри слов и составных конструкций — оставляем,
    # это правка финальной проверки на дефис уже в самом промпте
    # тут можем подстраховаться: уберём двойные/висячие пробелы
    result["html"] = re.sub(r"  +", " ", result["html"])
