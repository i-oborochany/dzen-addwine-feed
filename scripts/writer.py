def _brand_hint_for_theme(theme: str) -> str:
    t = theme.lower()
    if "штопор" in t:
        return BRAND_HINTS["штопоры"]
    if "бокал" in t:
        return BRAND_HINTS["бокалы"]
    if "декантер" in t or "аэратор" in t:
        return BRAND_HINTS["декантеры"]
    return ""


