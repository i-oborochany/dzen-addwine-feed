def load_topics() -> list:
    return json.loads(TOPICS_PATH.read_text(encoding="utf-8"))["topics"]


def load_categories() -> list:
    return json.loads(CATEGORIES_PATH.read_text(encoding="utf-8"))["categories"]


def pick_topic(used_titles: list, history: list = None) -> str:
    topics = load_topics()
    used_lower = [t.lower() for t in used_titles]
    fresh = [t for t in topics if not any(t.lower()[:30] in u for u in used_lower)]
    if not fresh:
        fresh = topics

    # Стоп-лист тем (не пишем про бокалы/штопоры/бренды AddWine)
    import stop_list
    filtered = stop_list.filter_topics(fresh)
    if filtered:
        fresh = filtered

    if history:
        import dedup
        no_dupes = dedup.filter_topics(fresh, history, days=90)
        if no_dupes:
            fresh = no_dupes
            print(f"  [dedup] после фильтра 90 дней осталось {len(fresh)} тем")
        else:
            print(f"  [dedup] ⚠️  все темы имеют семантический дубль за 90 дней")

    return fresh[0]


def pick_kitchen_category(topic: str) -> dict:
    """
    Выбирает подходящую подкатегорию кухни для нативной ссылки по теме статьи.
    """
    cats = load_categories()
    topic_low = topic.lower()

    keywords_map = {
        "Мельницы для специй": ["специи", "перец", "соль", "приправ", "остр", "карри", "азиат"],
        "Ножи": ["стейк", "мясо", "рыб", "разделк", "нарез", "сашими", "суши", "тартар", "утка", "птиц"],
        "Блюда для сервировки": ["сервиров", "стол", "подач", "гости", "ужин", "праздн", "новог", "паст"],
        "Формы для запекания": ["запек", "тушен", "оссо", "гриль", "духов", "фондю", "тартифлетт", "раклетт"],
        "Кофемолки": ["десерт", "тирамису", "кофе"],
        "Блендеры": ["соус", "пюре", "суп"],
    }

    for cat in cats:
        keys = keywords_map.get(cat["title"], [])
        if any(k in topic_low for k in keys):
            return cat

    return cats[0]  # блюда по умолчанию


def write_food_article(topic_idea: str, recent_titles: list, keywords_hint: str = "") -> dict:
    history = "\n".join(f"- {t}" for t in recent_titles[:30]) if recent_titles else "(пусто)"
    kitchen_cat = pick_kitchen_category(topic_idea)

    seo_block = f"\n\n{keywords_hint}\n" if keywords_hint else ""

    user = f"""ИДЕЯ ДЛЯ СТАТЬИ: {topic_idea}

Уже публиковали в этой рубрике (не повторяйся):
{history}

Нативно упомяни в одном месте статьи наш раздел аксессуаров: {kitchen_cat['title']} — {kitchen_cat['url']}
Формат: обычная HTML-ссылка внутри абзаца, органично встроенная в текст. Одна фраза, не CTA-блок.
{seo_block}
Напиши статью строго по правилам системного промпта. Ответ — JSON."""

    result = claude_api.generate_json(SYSTEM, user, max_tokens=8000, temperature=0.7)
    _validate(result)
    result["_kitchen_category"] = kitchen_cat
    return result


def _validate(result: dict) -> None:
    required = ["titles", "title_chosen", "lead", "html", "image_prompts", "comment_question", "categories"]
    for f in required:
        if f not in result:
            raise RuntimeError(f"Поле '{f}' отсутствует в ответе Claude")
    if len(result["image_prompts"]) < 1:
        raise RuntimeError("image_prompts пустой")
    result["image_prompts"] = result["image_prompts"][:1]

    cats = result.get("categories") or []
    if "Вино и еда" not in cats:
        cats = ["Вино и еда"] + [c for c in cats if c != "Вино и еда"]
    result["categories"] = cats[:2]

    result["html"] = re.sub(r"  +", " ", result["html"])
